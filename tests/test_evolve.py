"""`evolve` plans safe documentation changes and never grants compliance by itself."""

import importlib.util
import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    "autodoc_evolve", ROOT / "scripts/intelligence/evolve.py")
assert spec is not None and spec.loader is not None
evolve_module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(evolve_module)

CONFIG = """schema = 1
phase = "beta"
phase_declared = "2026-10-23"
audience = ["contributors", "external-users"]
"""


def write_project(path: Path, text: str = CONFIG) -> Path:
    (path / "README.md").write_text("# Consumer\n", encoding="utf-8")
    (path / "autodoc.toml").write_text(text, encoding="utf-8")
    return path


def action_ids(result: dict, kind: str) -> set[str]:
    return {action["id"] for action in result["actions"] if action["kind"] == kind}


def test_plan_is_read_only_and_finds_required_documents(tmp_path):
    write_project(tmp_path)

    result = evolve_module.build_plan(tmp_path)

    assert not (tmp_path / "docs").exists()
    assert result["phase"] == "beta"
    assert result["summary"]["actions"] == 9
    assert result["summary"]["documents"] == 9
    assert action_ids(result, "create_document") >= {
        "DEV-B01-001", "DEV-B01-002", "DEV-B01-003", "DEV-B01-006",
        "DEV-B04-001", "DEV-B04-002", "DEV-B05-001", "DEV-B10-001", "DEV-B10-003"}
    undetermined = {report["id"] for report in result["reports"]
                    if report["kind"] == "undetermined"}
    assert "DOC-A05-007" in undetermined
    assert result["maturity"]["level"] == "early"


def test_write_without_allow_add_does_not_create_documents(tmp_path):
    write_project(tmp_path)

    code, result = evolve_module.evolve(repo=tmp_path, write=True)

    assert code == 0
    assert result["summary"]["written"] == 0
    assert result["summary"]["pending"] == 9
    assert not (tmp_path / "docs").exists()


def test_allow_add_creates_drafts_but_never_registers_them(tmp_path):
    write_project(tmp_path)

    code, result = evolve_module.evolve(repo=tmp_path, write=True, allow_add=True)

    assert code == 0, result.get("errors")
    created = [action for action in result["actions"]
               if action["kind"] == "create_document" and action["written"]]
    assert len(created) == 9
    target = tmp_path / created[0]["target"]
    text = target.read_text(encoding="utf-8")
    assert "status: draft" in text
    assert (tmp_path / "autodoc.toml").read_text(encoding="utf-8") == CONFIG

    second = evolve_module.build_plan(tmp_path)
    unregistered = {report["id"] for report in second["reports"]
                    if report["kind"] == "unregistered"}
    assert {action["id"] for action in created} <= unregistered
    assert not action_ids(second, "create_document")


def test_existing_unregistered_document_is_reported_not_overwritten(tmp_path):
    write_project(tmp_path)
    target = next(action["target"] for action in evolve_module.build_plan(tmp_path)["actions"]
                  if action["id"] == "DEV-B01-001")
    destination = tmp_path / target
    destination.parent.mkdir(parents=True)
    destination.write_text("owner content\n", encoding="utf-8")

    result = evolve_module.evolve(repo=tmp_path, write=True, allow_add=True)[1]

    assert destination.read_text(encoding="utf-8") == "owner content\n"
    assert "DEV-B01-001" not in action_ids(result, "create_document")
    assert any(report["kind"] == "unregistered" and report["id"] == "DEV-B01-001"
               for report in result["reports"])


def test_generated_drift_is_planned_and_refreshed(tmp_path):
    write_project(tmp_path)
    (tmp_path / "docs/generated").mkdir(parents=True)
    (tmp_path / "docs/.doc-sync-map.yaml").write_text(json.dumps({
        "version": 1,
        "generated": [{
            "id": "outline",
            "sources": ["README.md"],
            "target": "docs/generated/OUTLINE.md",
            "generator": "outline",
        }],
    }), encoding="utf-8")
    target = tmp_path / "docs/generated/OUTLINE.md"
    target.write_text(
        "<!-- AUTO-GENERATED BY AUTODOC ENGINE. DO NOT EDIT. -->\n# stale\n",
        encoding="utf-8")

    plan = evolve_module.build_plan(tmp_path)
    assert any(action["kind"] == "refresh_generated"
               and action["target"] == "docs/generated/OUTLINE.md"
               for action in plan["actions"])

    code, result = evolve_module.evolve(repo=tmp_path, write=True)

    assert code == 0, result.get("errors")
    assert "Documentation outline" in target.read_text(encoding="utf-8")
    assert "Consumer" in target.read_text(encoding="utf-8")
    second = evolve_module.build_plan(tmp_path)
    assert not any(action["kind"] == "refresh_generated" for action in second["actions"])


def test_configuration_errors_block_every_write(tmp_path):
    write_project(tmp_path, """schema = 1
phase = "build"
phase_declared = "2026-10-23"
audience = ["contributors"]

[instantiated]
DOC-A03-001 = "docs/missing.md"
""")

    code, result = evolve_module.evolve(repo=tmp_path, write=True, allow_add=True)

    assert code == 2
    assert result["config_errors"]
    assert result["summary"]["written"] == 0
    assert not (tmp_path / "docs").exists()
    assert evolve_module.main(["--repo", str(tmp_path), "--check"]) == 2


def test_maturity_uses_observable_signals(tmp_path):
    (tmp_path / "LICENSE").write_text("license\n", encoding="utf-8")
    (tmp_path / "CHANGELOG.md").write_text("# Changelog\n", encoding="utf-8")
    (tmp_path / ".github/workflows").mkdir(parents=True)
    (tmp_path / ".github/workflows/ci.yml").write_text("on: push\n", encoding="utf-8")
    (tmp_path / "tests").mkdir()
    (tmp_path / "tests/test_consumer.py").write_text("def test_ok():\n    pass\n",
                                                     encoding="utf-8")
    (tmp_path / "pyproject.toml").write_text("[project]\nname = 'consumer'\n",
                                             encoding="utf-8")

    report = evolve_module.maturity(tmp_path)

    assert report["level"] == "growing"
    assert all(report["signals"][name] for name in ("license", "changelog", "ci", "tests", "package"))
    assert tomllib.loads((tmp_path / "pyproject.toml").read_text(encoding="utf-8"))
